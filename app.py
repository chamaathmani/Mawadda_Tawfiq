import streamlit as st

# إعدادات الصفحة الأساسية
st.set_page_config(
    page_title="منصة مودة والتوفيق",
    page_icon="⚖️",
    layout="wide"
)

# العنوان الرئيسي والشعار
st.title("⚖️ منصة مودة والتوفيق")
st.subheader("لخلق توازن عادل، وتوفيق دائم في عالم العمل")
st.markdown("---")

# القائمة الجانبية للتنقل بين الأقسام الأربعة للمنصة
st.sidebar.title("📌 أبواب المنصة الرئيسية")
selected_tab = st.sidebar.radio(
    "اختر الوحدة المطلوبة:",
    [
        "1️⃣ بوابة التشغيل (سوق العمل الرقمي)",
        "2️⃣ نافذة الحقوق والواجبات (المستشار الرقمي)",
        "3️⃣ غرفة التسوية البديلة للنزاعات",
        "4️⃣ النافذة المعرفية والبحثية"
    ]
)

# ---------------------------------------------------------
# الوحدة الأولى: بوابة التشغيل (سوق العمل الرقمي)
# ---------------------------------------------------------
if selected_tab == "1️⃣ بوابة التشغيل (سوق العمل الرقمي)":
    st.header("🌐 أولاً: بوابة التشغيل وسوق العمل الرقمي")
    st.write("إدارة فرص العمل، ربط الكفاءات بأصحاب العمل، وتوفير قوالب عقود ذكية متوافقة مع فقه الإجارة وقانون العمل.")
    
    tab1, tab2, tab3 = st.tabs(["الباحثون عن عمل", "أصحاب العمل والشركات", "قوالب العقود الذكية"])
    
    with tab1:
        st.subheader("👤 الباحثون عن عمل")
        job_seeker_name = st.text_input("الاسم الكامل:")
        job_seeker_skills = st.text_area("أبرز المهارات والتخصصات:")
        if st.button("تسجيل السيرة الذاتية"):
            if job_seeker_name:
                st.success(f"مرحباً بكِ {job_seeker_name}! تم حفظ بياناتك في قاعدة بيانات الباحثين عن عمل بنجاح.")
            else:
                st.warning("يرجى إدخال الاسم على الأقل.")
                
    with tab2:
        st.subheader("🏢 أصحاب العمل والشركات")
        company_name = st.text_input("اسم المؤسسة أو الشركة:")
        job_title = st.text_input("المسمى الوظيفي الشاغر:")
        if st.button("نشر الإعلان الوظيفي"):
            if company_name and job_title:
                st.success(f"تم نشر الإعلان الخاص بوظيفة ({job_title}) لصالح شركة ({company_name}) بنجاح!")
            else:
                st.warning("يرجى ملء تفاصيل الإعلان.")
                
    with tab3:
        st.subheader("📜 العقود النموذجية الموحدة")
        st.info("عقود عمل ذكية متوافقة مع ضوابط الإجارة الشرعية والنصوص الوضعية لقانون العمل الجزائري.")
        contract_type = st.selectbox("اختر نوع العقد:", ["عقد عمل غير محدد المدة (CDI)", "عقد عمل محدد المدة (CDD)"])
        st.write(f"الخصائص المعتمدة لـ: **{contract_type}** تشمل تحديد الأجر بوضوح، ساعات العمل القانونية، والضمانات الشرعية للطرفين.")

# ---------------------------------------------------------
# الوحدة الثانية: نافذة الحقوق والواجبات (المستشار الرقمي)
# ---------------------------------------------------------
elif selected_tab == "2️⃣ نافذة الحقوق والواجبات (المستشار الرقمي)":
    st.header("📖 ثانياً: نافذة الحقوق والواجبات (المستشار الرقمي)")
    st.write("دليل مبسط ومرجع فقهي وقانوني ينظم حقوق وواجبات كل طرف بوضوح تام.")
    
    choice = st.selectbox("اختر الباب المطلوب للاستعلام:", ["دليل العامل وصاحب العمل", "الزاوية الشرعية والقانونية المقارنة"])
    
    if choice == "دليل العامل وصاحب العمل":
        st.markdown("### 📋 الخلاصة الإرشادية:")
        st.write("- **الأجور:** وجوب الوفاء بالأجر فور استحقاقه مصداقاً لقوله صلى الله عليه وسلم: (أعطوا الأجير أجره قبل أن يجف عرقه)، ومقابله المادة القانونية المحددة لمواعيد الدفع.")
        st.write("- **ساعات العمل والإجازات:** الالتزام بالحد الأسبوعي القانوني وضمان الإجازات السنوية المدفوعة.")
        st.write("- **مكافأة نهاية الخدمة وشروط الفصل:** التأكيد على الضوابط المشددة للفصل التعسفي وضرورة الإخطار المسبق.")
    else:
        st.markdown("### ⚖️ التأصيل الشرعي والنصوص الوضعية:")
        st.write("تتعرض هذه النافذة للفتاوى المعاصرة المرتبطة بقضايا العمل والأجور، ومقارنتها بمواد القانون المدني وقانون العمل الجزائري لضمان التكامل الرقمي.")

# ---------------------------------------------------------
# الوحدة الثالثة: غرفة التسوية البديلة للنزاعات
# ---------------------------------------------------------
elif selected_tab == "3️⃣ غرفة التسوية البديلة للنزاعات":
    st.header("🤝 ثالثاً: غرفة التسوية البديلة للنزاعات (ADR)")
    st.write("منصة الوساطة والصلح الإلكتروني لتقريب وجهات النظر وفض النزاعات العمالية ودياً.")
    
    dispute_type = st.selectbox("طبيعة النزاع العمالي:", ["تأخر أو عدم دفع الأجور", "فصل تعسفي محتمل", "نزاعات بيئة العمل وساعات الإضافي"])
    complainant = st.text_input("اسم الشاكي (عامل / صاحب عمل):")
    dispute_details = st.text_area("تفاصيل الشكوى وموضوع النزاع:")
    
    if st.button("تقديم طلب الصلح والوساطة"):
        if complainant and dispute_details:
            st.success("تم تسجيل طلب الوساطة الإلكترونية بنجاح وتم منحه رقماً مرجعياً مؤقتاً لتوجيهه نحو لجنة التحكيم والصلح الودي.")
        else:
            st.warning("يرجى ملء جميع الحقول المطلوبة لتقديم الشكوى.")

# ---------------------------------------------------------
# الوحدة الرابعة: النافذة المعرفية والبحثية
# ---------------------------------------------------------
else:
    st.header("📚 رابعاً: النافذة المعرفية والبحثية")
    st.write("المكتبة الرقمية والمراجع العلمية المتخصصة في دراسات العمل والتحول الرقمي في فض النزاعات.")
    
    st.markdown("### 🔍 المقالات والأبحاث المنشورة:")
    st.markdown("1. *دور التحول الرقمي في تسوية النزاعات العمالية: دراسة تحليلية مقارنة بين الشريعة والقانون.*")
    st.markdown("2. *أحكام الأجير في فقه المعاملات الإسلامية وتطبيقاتها في تشريعات العمل المعاصرة.*")
    st.markdown("3. *آليات الوساطة والتحكيم الإلكتروني كبديل ناجع للتقاضي العمالي التقليدي.*")

